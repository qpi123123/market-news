def _pattern(word: str) -> re.Pattern:
    # 영문 키워드는 단어 경계로 매칭 (예: "AI"가 "SAID"에 걸리지 않게)
    if re.fullmatch(r"[A-Za-z&]+", word):
        return re.compile(rf"(?<![A-Za-z]){re.escape(word)}(?![A-Za-z])")
    return re.compile(re.escape(word))


_COMPILED: dict[str, re.Pattern] = {}


def find(text: str, words: list[str]) -> list[str]:
    """text에 등장하는 단어 목록."""
    hits = []
    for w in words:
        pat = _COMPILED.get(w) or _COMPILED.setdefault(w, _pattern(w))
        if pat.search(text):
            hits.append(w)
    return hits


